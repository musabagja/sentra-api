import express from 'express';
import UserController from '../../controllers/user.controller';
import UserAdminController from '../../controllers/user-admin.controller';
import Permissions from '../../middlewares/permission.handler';
import { USER_ACCESS } from '../../utils/access.util';

const router = express.Router();

// ============================================================================
// USER MANAGEMENT ROUTES (User menu)
// ============================================================================

// PUT /api/users/me/password - The signed-in user changes their own password (login only,
// no access needed; must stay before /:code)
router.put('/me/password', UserController.changeOwnPassword);

// GET /api/users - List users (all circles), paginated
router.get('/', Permissions.require(USER_ACCESS.MENU), UserAdminController.getUsers);

// GET /api/users/accesses - Accesses that can be granted from the form (must stay before /:code)
router.get('/accesses', Permissions.require(USER_ACCESS.MENU), UserAdminController.getAccessOptions);

// POST /api/users - Create a user (code generated by the server)
router.post('/', Permissions.require(USER_ACCESS.ADD), UserAdminController.createUser);

// GET /api/users/code-check?code= and /code-suggestion - the code field of the create form
// (must stay before /:code)
router.get('/code-check', Permissions.require(USER_ACCESS.ADD), UserAdminController.checkCode);
router.get('/code-suggestion', Permissions.require(USER_ACCESS.ADD), UserAdminController.suggestCode);

// GET /api/users/:code - One user with their accesses
router.get('/:code', Permissions.require(USER_ACCESS.MENU), UserAdminController.getUser);

// PUT /api/users/:code - Update name, circle, accesses or reset the password
router.put('/:code', Permissions.require(USER_ACCESS.EDIT), UserAdminController.updateUser);

// POST /api/users/:code/freeze - Freeze: can't sign in, signed out everywhere
router.post('/:code/freeze', Permissions.require(USER_ACCESS.FREEZE), UserAdminController.setFrozen(true));

// POST /api/users/:code/unfreeze - Let a frozen user sign in again
router.post('/:code/unfreeze', Permissions.require(USER_ACCESS.FREEZE), UserAdminController.setFrozen(false));

export default router;
